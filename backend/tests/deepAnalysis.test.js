const assert=require('node:assert/strict'),crypto=require('node:crypto');
const {createService}=require('../src/reasoning/deepAnalysis');
const source=(text)=>({path:'src/sample.js',complete:true,version:crypto.createHash('sha256').update(text).digest('hex'),text:text.split('\n').map((l,i)=>`${i+1}: ${l}`).join('\n')});
const current=source('function sample(text){if(!text)return "empty";return text;}');
const answer={claims:[{kind:'behavior',text:'Returns the supplied value when truthy.',assumptions:[],citations:[{path:current.path,line:1}]}],unknowns:[],examples:[]};
const envelope=()=>({done:true,done_reason:'stop',message:{role:'assistant',content:JSON.stringify(answer),thinking:'do not retain this'}});
const command={filename:current.path,question:'Deep analyze the sample file.'};
const options={agentId:'alice',completeEnvelope:async(messages,opts)=>{assert.equal(opts.think,true);assert.equal(opts.temperature,0);assert(opts.format);return envelope();}};
async function main(){
    const service=createService({read:async()=>current});
    const result=await service.answer(command,options);
    const routed=await require('../src/reasoning/projectQuestion').createService({read:async()=>current,repository:{get:()=>{throw new Error('Deep analysis must not read stored knowledge.');}}}).answer({...command,deepAnalysis:true},options);
    assert.equal(routed.deepAnalysis,true);
    assert.equal(result.analysis.status,'unverified');assert.match(result.reply,/not independently verified/);
    assert.match(result.reply,/Source evidence:/);assert.match(result.reply,/Deterministic analyzer limits:/);
    assert.match(result.reply,/Recorded dependency source gaps: none within the inspected scope/);
    assert(result.reply.indexOf(answer.claims[0].text)<result.reply.indexOf('Evidence notes:'));
    assert.equal(result.integrity.thinkingChars,18);assert(!JSON.stringify(result).includes('do not retain this'));
    assert(!result.speech.includes('src/'));assert.equal(result.coverage.target.name,'sample');
    const followup=await service.answer({...command,question:'What does that function do?',contextQuestion:command.question,targetSymbol:'sample'},options);
    assert.equal(followup.coverage.target.name,'sample');
    assert.match(followup.reply,/Deterministic analyzer limits: \d+ recorded/);
    assert.match(followup.reply,/Recorded dependency source gaps: none within the inspected scope/);
    const unknown={kind:'runtime_state',detail:'The caller input is unspecified.',blockedConclusion:'Which value was passed in the actual invocation?',neededEvidence:'The recorded argument for that invocation.'};
    const uncertain=await service.answer(command,{...options,completeEnvelope:async()=>({...envelope(),message:{role:'assistant',content:JSON.stringify({...answer,unknowns:[unknown]})}})});
    assert.match(uncertain.reply,/Blocked conclusion: Which value was passed/);
    assert.match(uncertain.speech,/proposes open questions.*not been verified/);
    await assert.rejects(service.answer(command,{...options,isCancelled:()=>true}),/cancelled/);
    await assert.rejects(service.answer(command,{...options,completeEnvelope:async()=>({...envelope(),done_reason:'length'})}),/incomplete/);
    await assert.rejects(service.answer(command,{...options,completeEnvelope:async()=>({...envelope(),message:{role:'assistant',content:'Let me think\n'+JSON.stringify(answer)}})}),/withheld/);
    await assert.rejects(service.answer(command,{...options,completeEnvelope:async()=>({...envelope(),message:{role:'assistant',content:'{}'}})}),/fields/);
    let called=false;
    await assert.rejects(createService({read:async()=>source('function sample(){return "</think>";}')}).answer(command,{...options,completeEnvelope:async()=>{called=true;return envelope();}}),/channel tags/);
    assert.equal(called,false);
    let reads=0;
    await assert.rejects(createService({read:async()=>++reads<=2?current:source('function sample(){return 2;}')}).answer(command,options),/changed/);
    let resolve,signal;
    const slow=createService({read:async()=>current,timeoutMs:10});
    await assert.rejects(slow.answer(command,{...options,completeEnvelope:async(m,o)=>{signal=o.signal;return new Promise(r=>{resolve=r;});}}),/timed out/);
    assert(signal.aborted);
    await assert.rejects(service.answer(command,options),/already running/);
    resolve(envelope());await new Promise(r=>setImmediate(r));
    await service.answer(command,options);
    let cancelled=false;
    const cancelling=service.answer(command,{...options,isCancelled:()=>cancelled,completeEnvelope:(m,o)=>new Promise((resolve,reject)=>{cancelled=true;o.signal.addEventListener('abort',()=>reject(new Error('cancelled')));})});
    await assert.rejects(cancelling,/cancelled/);
    await new Promise(r=>setImmediate(r));
    console.log('Deep analysis: fresh source, unverified output, no retained thinking, schema rejection, tag guard, timeout, cancellation and sequential calls passed.');
}
main().catch(e=>{console.error(e);process.exitCode=1;});
